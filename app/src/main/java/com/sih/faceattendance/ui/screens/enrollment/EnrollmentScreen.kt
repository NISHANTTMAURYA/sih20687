                                                                            holdProgress = 0f
                                                                            guidanceMessage = "Now slowly turn your head LEFT 👈"
                                                                        }
                                                                    }
                                                                    3 -> {
                                                                        // Turn Head Right: User must turn head RIGHT (userYaw >= 13f)
