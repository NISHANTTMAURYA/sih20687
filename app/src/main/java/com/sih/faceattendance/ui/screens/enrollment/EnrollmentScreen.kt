                                                                        } else if (userYaw <= -10f) {
                                                                            // User turned the WRONG way (turned left)!
                                                                            holdCount = 0
                                                                            holdProgress = 0f
                                                                            guidanceMessage = "You turned LEFT! Please turn RIGHT 👉"
                                                                        } else {
                                                                            holdCount = 0
                                                                            holdProgress = 0f
                                                                            guidanceMessage = "Now slowly turn your head RIGHT 👉"
