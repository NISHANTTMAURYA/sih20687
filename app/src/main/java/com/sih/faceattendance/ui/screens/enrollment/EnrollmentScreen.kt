                                ) {
                                    Column(
                                        horizontalAlignment = Alignment.CenterHorizontally,
                                        verticalArrangement = Arrangement.spacedBy(8.dp),
                                        modifier = Modifier.padding(12.dp)
                                    ) {
                                        Icon(
                                            imageVector = Icons.Default.CheckCircle,
                                            contentDescription = "Success",
                                            tint = Color.White,
                                            modifier = Modifier.size(44.dp)
                                        )
                                        Text(
                                            text = "4 BIOMETRIC CHECKS VERIFIED!",
                                            color = Color.White,
                                            fontWeight = FontWeight.Bold,
                                            fontSize = 12.sp,
                                            letterSpacing = 0.5.sp
                                        )
                                        Row(
                                            horizontalArrangement = Arrangement.spacedBy(6.dp),
                                            verticalAlignment = Alignment.CenterVertically
                                        ) {
                                            capturedFrontFaceBitmap?.let { bmp ->
                                                Image(
                                                    bitmap = bmp.asImageBitmap(),
                                                    contentDescription = "Front",
                                                    modifier = Modifier
                                                        .size(46.dp)
                                                        .clip(CircleShape)
                                                        .border(2.dp, Color.White, CircleShape),
                                                    contentScale = ContentScale.Crop
                                                )
                                            }
                                            capturedLeftFaceBitmap?.let { bmp ->
                                                Image(
                                                    bitmap = bmp.asImageBitmap(),
                                                    contentDescription = "Left",
                                                    modifier = Modifier
                                                        .size(46.dp)
                                                        .clip(CircleShape)
                                                        .border(2.dp, Color.White, CircleShape),
                                                    contentScale = ContentScale.Crop
                                                )
                                            }
                                            capturedRightFaceBitmap?.let { bmp ->
                                                Image(
                                                    bitmap = bmp.asImageBitmap(),
                                                    contentDescription = "Right",
                                                    modifier = Modifier
                                                        .size(46.dp)
                                                        .clip(CircleShape)
                                                        .border(2.dp, Color.White, CircleShape),
                                                    contentScale = ContentScale.Crop
                                                )
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }

                    // Live Head Angle Pill Feedback
                    Surface(
                        color = LightSubtle,
                        shape = RoundedCornerShape(8.dp),
                        border = androidx.compose.foundation.BorderStroke(1.dp, LightCardBorder)
                    ) {
                        Row(
                            modifier = Modifier.padding(horizontal = 12.dp, vertical = 6.dp),
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(6.dp)
                        ) {
                            Icon(
                                imageVector = if (faceDetectedInCircle) Icons.Default.Face else Icons.Default.FaceRetouchingOff,
                                contentDescription = null,
                                tint = if (faceDetectedInCircle) PrimaryBlue else TextMuted,
                                modifier = Modifier.size(16.dp)
                            )
                            val poseText = when {
                                !faceDetectedInCircle -> "Looking for face..."
                                abs(currentYaw) <= 10f -> "Frontal (0°)"
                                currentYaw < -10f -> "Left (${currentYaw.toInt()}°)"
                                else -> "Right (+${currentYaw.toInt()}°)"
                            }
                            Text(
                                text = "Head Pose: $poseText",
                                fontSize = 11.sp,
                                fontWeight = FontWeight.SemiBold,
                                color = if (faceDetectedInCircle) TextPrimary else TextMuted
                            )
                        }
                    }

                    // 4 Step Badges (Front, Left, Right, Blink)
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceEvenly
                    ) {
                        AngleBadge("1. Front", registrationStep > 1)
                        AngleBadge("2. Left", registrationStep > 2)
                        AngleBadge("3. Right", registrationStep > 3)
                        AngleBadge("4. Blink", registrationStep > 4)
                    }

                    // Duplicate Conflict Error in Modal
                    if (duplicateErrorText != null) {
                        Surface(
                            color = CrimsonContainer,
                            shape = RoundedCornerShape(12.dp),
                            border = androidx.compose.foundation.BorderStroke(1.dp, CrimsonAlert.copy(alpha = 0.5f))
                        ) {
                            Column(
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(12.dp),
                                verticalArrangement = Arrangement.spacedBy(8.dp)
                            ) {
                                Row(
                                    verticalAlignment = Alignment.CenterVertically,
                                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                                ) {
                                    Icon(Icons.Default.Warning, contentDescription = null, tint = CrimsonAlert)
                                    Text(
                                        text = duplicateErrorText!!,
                                        color = CrimsonAlert,
                                        fontSize = 11.sp,
                                        fontWeight = FontWeight.Medium,
                                        lineHeight = 15.sp
                                    )
                                }

                                if (conflictingStudent != null && pendingAggregatedVector != null) {
                                    Button(
                                        onClick = {
                                            val vec = pendingAggregatedVector!!
                                            val front = capturedFrontFaceBitmap ?: latestFrameBitmap
                                            if (front != null) {
                                                registerStudentWithVector(vec, front)
                                            }
                                        },
                                        modifier = Modifier.fillMaxWidth().height(42.dp),
                                        colors = ButtonDefaults.buttonColors(containerColor = CrimsonAlert),
                                        shape = RoundedCornerShape(8.dp)
                                    ) {
                                        Icon(Icons.Default.DeleteSweep, contentDescription = null, modifier = Modifier.size(16.dp))
                                        Spacer(Modifier.width(6.dp))
                                        Text(
                                            text = "DELETE '${conflictingStudent!!.name}' & RE-ENROL NOW",
                                            fontSize = 11.sp,
                                            fontWeight = FontWeight.Bold
                                        )
                                    }
                                }
                            }
                        }
                    }

                    // Action Controls: Restart & Manual Fallback Button
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(10.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        OutlinedButton(
                            onClick = {
                                capturedVectors.clear()
                                capturedFrontFaceBitmap = null
                                capturedLeftFaceBitmap = null
                                capturedRightFaceBitmap = null
                                registrationStep = 1
                                blinkDetected = false
                                holdCount = 0
                                holdProgress = 0f
                                firstTurnDirection = 0
                                isProcessingAngle = false
                                isSuccessAnimation = false
                                duplicateErrorText = null
                                conflictingStudent = null
                                pendingAggregatedVector = null
                                guidanceMessage = "Look straight at the camera"
                            },
                            shape = RoundedCornerShape(10.dp),
                            modifier = Modifier.weight(1f)
                        ) {
                            Icon(Icons.Default.RestartAlt, contentDescription = null, modifier = Modifier.size(16.dp))
                            Spacer(Modifier.width(4.dp))
                            Text("Reset", fontSize = 13.sp)
                        }

                        // Manual Capture Override Button
                        Button(
                            onClick = {
                                val frame = latestFrameBitmap
                                if (frame != null) {
                                    scope.launch {
                                        val faces = app.faceDetectorEngine.detectFaces(frame, 0)
                                        if (faces.isNotEmpty()) {
                                            if (registrationStep <= 3) {
                                                captureCurrentAngle(registrationStep, frame, faces[0])
                                            } else if (registrationStep == 4) {
                                                registrationStep = 5
                                                finalizeRegistration(capturedFrontFaceBitmap ?: frame)
                                            }
                                        }
                                    }
                                }
                            },
                            shape = RoundedCornerShape(10.dp),
                            modifier = Modifier.weight(2f),
                            colors = ButtonDefaults.buttonColors(containerColor = PrimaryBlue),
                            enabled = !isProcessingAngle && registrationStep <= 4
                        ) {
                            if (isProcessingAngle) {
                                CircularProgressIndicator(modifier = Modifier.size(18.dp), color = Color.White)
                                Spacer(Modifier.width(6.dp))
                                Text("Processing...", fontSize = 13.sp)
                            } else {
                                Icon(Icons.Default.CameraAlt, contentDescription = null, modifier = Modifier.size(16.dp))
                                Spacer(Modifier.width(6.dp))
                                Text(
                                    if (registrationStep == 4) "Verify Blink & Register" else "Manual Capture (${registrationStep}/4)",
                                    fontSize = 12.sp,
                                    fontWeight = FontWeight.Bold
                                )
                            }
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun AngleBadge(label: String, isDone: Boolean) {
    Surface(
        color = if (isDone) EmeraldContainer else LightSubtle,
        shape = RoundedCornerShape(8.dp),
        border = androidx.compose.foundation.BorderStroke(
            1.dp,
            if (isDone) EmeraldVerified.copy(alpha = 0.5f) else LightCardBorder
        )
    ) {
        Row(
            modifier = Modifier.padding(horizontal = 10.dp, vertical = 6.dp),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(4.dp)
        ) {
            Icon(
                imageVector = if (isDone) Icons.Default.CheckCircle else Icons.Default.RadioButtonUnchecked,
                contentDescription = null,
                tint = if (isDone) EmeraldVerified else TextMuted,
                modifier = Modifier.size(14.dp)
            )
            Text(
                text = label,
                fontSize = 11.sp,
                fontWeight = if (isDone) FontWeight.Bold else FontWeight.Normal,
                color = if (isDone) EmeraldVerified else TextSecondary
            )
        }
    }
}

@Composable
private fun AnglePhotoItem(label: String, bitmap: Bitmap?) {
    Column(
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.spacedBy(4.dp)
    ) {
        Surface(
            shape = RoundedCornerShape(10.dp),
            border = androidx.compose.foundation.BorderStroke(1.dp, PrimaryBlue.copy(alpha = 0.35f)),
            color = LightSurface,
            modifier = Modifier.size(72.dp)
        ) {
            if (bitmap != null) {
                Image(
                    bitmap = bitmap.asImageBitmap(),
                    contentDescription = label,
                    modifier = Modifier.fillMaxSize(),
                    contentScale = ContentScale.Crop
                )
            } else {
                Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                    Icon(Icons.Default.Face, contentDescription = null, tint = TextMuted)
                }
            }
        }
        Text(
            text = label,
            fontSize = 10.sp,
            fontWeight = FontWeight.SemiBold,
            color = TextSecondary
        )
    }
}
