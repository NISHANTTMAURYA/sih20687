                                                                    }
                                                                    4 -> {
                                                                        // Step 4: Liveness Challenge - Blink Both Eyes
                                                                        val leftEye = face.leftEyeOpenProbability ?: 1.0f
                                                                        val rightEye = face.rightEyeOpenProbability ?: 1.0f
